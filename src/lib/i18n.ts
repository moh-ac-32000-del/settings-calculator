const ar: Record<TranslationKey, string> = Object.fromEntries(
  Object.keys(tr).map((key) => [key, key]),
) as Record<TranslationKey, string>;
const dictionaries: Record<AppLanguage, Record<TranslationKey, string>> = { ar, tr, en };

export const languageOptions = [
  { code: 'ar' as const, labelKey: 'العربية' as TranslationKey },
  { code: 'tr' as const, labelKey: 'Türkçe' as TranslationKey },
  { code: 'en' as const, labelKey: 'English' as TranslationKey },
];

export function normalizeLanguage(value: unknown): AppLanguage {
  return value === 'en' || value === 'tr' || value === 'ar' ? value : 'ar';
}
export function isRTL(language: AppLanguage): boolean { return language === 'ar'; }
export function getLanguageLocale(language: AppLanguage): string {
  return language === 'ar' ? 'ar-SA' : language === 'tr' ? 'tr-TR' : 'en-US';
}
export function formatLocalizedDate(date: Date, language: AppLanguage): string {
  return new Intl.DateTimeFormat(getLanguageLocale(language), { day:'2-digit', month:'long', year:'numeric', numberingSystem:'latn' }).format(date);
}
export function formatLocalizedTime(date: Date, language: AppLanguage): string {
  return new Intl.DateTimeFormat(getLanguageLocale(language), { hour:'2-digit', minute:'2-digit', numberingSystem:'latn' }).format(date);
}
export function translate(key: TranslationKey, language: AppLanguage = 'ar'): string {
  return dictionaries[language][key] ?? ar[key] ?? key;
}
